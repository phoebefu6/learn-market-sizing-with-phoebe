"""Build assets/msz-sample.js with json.dumps (never string interpolation).
Real rows: materials/fies-drinks-2023-2025.csv (Statistics Bureau of Japan, FIES ranking, 2023-2025 average,
two-or-more-person households, yen per household per year) and the 2020 Census household counts
(Basic Complete Tabulation on Population and Households, outline Table I-4-2, read at source).
Everything about Kettle & Co is CONSTRUCTED and labelled so in the data.
Usage: python3 materials/build-sample.py
"""
import csv, json, os

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
COLS = ["tea_all_yen", "green_leaf_yen", "green_leaf_g", "black_leaf_yen", "black_leaf_g", "other_leaf_yen",
        "other_leaf_g", "tea_drinks_yen", "lactic_drinks_yen", "mineral_water_yen", "sports_drinks_yen"]

def load_rows():
    rows = []
    with open(os.path.join(HERE, "fies-drinks-2023-2025.csv"), encoding="utf-8") as f:
        for r in csv.DictReader(f):
            vals = [int(r[c]) for c in COLS]
            d = dict(zip(COLS, vals))
            # the survey's tea total is the sum of its four tea items, to within the rounding of
            # published averages (exact for the national row; off by 1 or 2 yen in 15 city rows)
            parts = d["green_leaf_yen"] + d["black_leaf_yen"] + d["other_leaf_yen"] + d["tea_drinks_yen"]
            assert abs(d["tea_all_yen"] - parts) <= 2, r["city"]
            rows.append([r["city"]] + vals)
    return rows

ROWS = load_rows()
